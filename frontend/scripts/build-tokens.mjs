// Emits the dark theme twice — OS preference (unless the user picked light) and explicit toggle —
// from one source, so the two copies can never drift (§4.5.1, T-405).
import { writeFileSync } from 'node:fs';
import dark from '../src/styles/tokens.dark.js';

const body = Object.entries(dark)
  .map(([k, v]) => `    ${k}: ${v};`)
  .join('\n');
const css = `/* GENERATED by scripts/build-tokens.mjs from tokens.dark.js. Do not edit. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${body}
  }
}

:root[data-theme='dark'] {
${body.replaceAll('\n    ', '\n  ').replace(/^ {4}/, '  ')}
}
`;
writeFileSync(new URL('../src/styles/tokens.generated.css', import.meta.url), css);
console.log('tokens.generated.css written');
